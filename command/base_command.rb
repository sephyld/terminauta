# frozen_string_literal: true

module Terminauta
  module Command
    # Inherit from this class to build a command line command:
    #
    #   class Todo::Command < Terminauta::Command::BaseCommand
    #     description "Manage a todo list"
    #
    #     option :name, short: '-n', value: 'NAME', description: 'Name of the item'
    #     option :verbose, description: 'Print extra output'
    #
    #     subcommand "add", Todo::Commands::Add
    #
    #     def run
    #       # args, arguments and options are available here
    #     end
    #   end
    #
    # The class level DSL lives in ClassMethods, dispatch in Dispatch,
    # parsing in Parsing and help rendering in Help. Plain output and
    # yes/no prompts live in Io, colored output in ColoredCommand's Ui
    # (see Ui). Only spinel-safe features are used: no eval, no
    # method_missing and no dynamically defined methods.
    class BaseCommand
      extend ClassMethods
      include Help
      include Dispatch
      include Parsing
      include Io

      # Explicit readers instead of attr_reader: spinel miscompiles
      # `local = args[0]` in subclasses when the accessors are generated by
      # attr_reader while a module mutates the ivar (the local ends up
      # holding the index instead of the element). Plain methods compile
      # correctly under both spinel and MRI.
      def args
        @args
      end

      # The parsed arguments hash, keyed by the declared argument name
      # (both string and symbol keys), mirroring #options.
      def arguments
        @arguments
      end

      def options
        @options
      end

      # The command this one was dispatched from, or nil for the root
      # command. Set by the parent's dispatch through .execute.
      def parent_command
        @parent_command
      end

      def initialize(argv = [], parent_command = nil)
        @argv = argv
        @args = []
        @arguments = {}
        @options = {}
        @subcommand_argv = nil
        @parent_command = parent_command
        parse_argv
      end

      # Override this in subclasses with the actual command behavior. An
      # Integer return value is used as the process exit status.
      def run
        raise NotImplementedError, "#{self.class} must implement #run"
      end
    end
  end
end
